using Carteiro.Domain;
using Microsoft.EntityFrameworkCore;

namespace Carteiro.Data;

public sealed class CarteiroDbContext(DbContextOptions<CarteiroDbContext> options) : DbContext(options)
{
    /// <summary>
    /// Deliveries in these states are the work queue. The partial index on next_attempt_at and
    /// the claim query in the dispatcher must agree on this list.
    /// </summary>
    public const string ClaimableStatusesSql = "'Pending', 'Failed'";

    public DbSet<WebhookEndpoint> Endpoints => Set<WebhookEndpoint>();

    public DbSet<Event> Events => Set<Event>();

    public DbSet<Delivery> Deliveries => Set<Delivery>();

    public DbSet<DeliveryAttempt> DeliveryAttempts => Set<DeliveryAttempt>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<WebhookEndpoint>(endpoint =>
        {
            endpoint.ToTable("endpoints");
            endpoint.HasKey(e => e.Id);

            // Ids are generated by the application (UUIDv7). Telling EF so also makes it treat
            // new objects found through navigations as inserts rather than updates.
            endpoint.Property(e => e.Id).ValueGeneratedNever();
            endpoint.Property(e => e.Url).HasMaxLength(2048);
            endpoint.Property(e => e.Description).HasMaxLength(500);
            endpoint.Property(e => e.Secret).HasMaxLength(255);
            endpoint.Property(e => e.EventTypes).HasColumnType("text[]");
            endpoint.Property(e => e.DisabledReason).HasMaxLength(500);
        });

        modelBuilder.Entity<Event>(@event =>
        {
            @event.ToTable("events");
            @event.HasKey(e => e.Id);
            @event.Property(e => e.Id).ValueGeneratedNever();
            @event.Property(e => e.Type).HasMaxLength(100);
            @event.Property(e => e.Payload).HasColumnType("text");
            @event.Property(e => e.IdempotencyKey).HasMaxLength(255);

            // This index is what makes idempotency safe under concurrency: two requests racing
            // with the same key cannot both insert. NULL keys do not conflict with each other.
            @event.HasIndex(e => e.IdempotencyKey).IsUnique();
        });

        modelBuilder.Entity<Delivery>(delivery =>
        {
            delivery.ToTable("deliveries");
            delivery.HasKey(d => d.Id);
            delivery.Property(d => d.Id).ValueGeneratedNever();
            delivery.Property(d => d.Status).HasConversion<string>().HasMaxLength(20);
            delivery.Property(d => d.LastError).HasMaxLength(2000);

            delivery.HasOne(d => d.Event)
                .WithMany()
                .HasForeignKey(d => d.EventId)
                .OnDelete(DeleteBehavior.Cascade);

            delivery.HasOne(d => d.Endpoint)
                .WithMany()
                .HasForeignKey(d => d.EndpointId)
                .OnDelete(DeleteBehavior.Cascade);

            delivery.HasMany(d => d.Attempts)
                .WithOne()
                .HasForeignKey(a => a.DeliveryId)
                .OnDelete(DeleteBehavior.Cascade);

            // An event is delivered to an endpoint at most once as a logical delivery.
            delivery.HasIndex(d => new { d.EventId, d.EndpointId }).IsUnique();

            // The work queue. Partial, so it only contains rows the worker can still act on
            // and stays small no matter how much history accumulates.
            delivery.HasIndex(d => d.NextAttemptAt)
                .HasDatabaseName("ix_deliveries_due")
                .HasFilter($"status IN ({ClaimableStatusesSql})");

            delivery.HasIndex(d => new { d.EndpointId, d.CreatedAt });
        });

        modelBuilder.Entity<DeliveryAttempt>(attempt =>
        {
            attempt.ToTable("delivery_attempts");
            attempt.HasKey(a => a.Id);
            attempt.Property(a => a.Id).ValueGeneratedNever();
            attempt.Property(a => a.Error).HasMaxLength(2000);
            attempt.HasIndex(a => new { a.DeliveryId, a.AttemptNumber });
        });
    }
}
